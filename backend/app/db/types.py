"""Reusable column types and helpers shared by module models."""

from __future__ import annotations

import enum
import uuid

from geoalchemy2 import Geography
from sqlalchemy import Enum, String, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column

# WGS 84 lat/lon - what browsers' geolocation API and OpenStreetMap use.
SRID_WGS84 = 4326


def pg_enum(enum_cls: type[enum.Enum], name: str) -> Enum:
    """Native PostgreSQL ENUM that stores the Python enum *values* (e.g. ``'citizen'``)."""
    return Enum(
        enum_cls,
        name=name,
        native_enum=True,
        validate_strings=True,
        values_callable=lambda members: [member.value for member in members],
    )


def geography_point():
    """``GEOGRAPHY(POINT, 4326)``. Distances on geography are in metres on the WGS 84 spheroid.

    ``spatial_index=False`` because every GiST index is declared explicitly (with a stable
    name) in the model's ``__table_args__`` and in the migration.
    Includes a SQLite fallback to allow fast in-memory unit testing.
    """
    return Geography(geometry_type="POINT", srid=SRID_WGS84, spatial_index=False).with_variant(
        String, "sqlite"
    )


def vector_column(dim: int = 384):
    """VECTOR(dim) for pgvector on PostgreSQL with JSON fallback on SQLite."""
    try:
        from pgvector.sqlalchemy import Vector
        from sqlalchemy.types import JSON

        return Vector(dim).with_variant(JSON, "sqlite")
    except ImportError:
        from sqlalchemy.dialects.postgresql import JSONB
        from sqlalchemy.types import JSON

        return JSON().with_variant(JSONB, "postgresql")


class UUIDPrimaryKeyMixin:
    """UUID v4 primary key generated by the database (``gen_random_uuid()``, core since PG 13)."""

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=text("gen_random_uuid()"),
    )
