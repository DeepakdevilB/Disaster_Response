"""Local LLM summarization service using Ollama with deterministic fallback (T-034).

Follows project architecture rules:
- Free and local (INR 0 budget, Ollama localhost)
- Advisory only: schema-validated, never dispatches resources
- Graceful degradation: if Ollama is not running, falls back to deterministic extractive summary.
"""

from __future__ import annotations

import json
import logging
from typing import Any

import httpx
from pydantic import BaseModel, Field

logger = logging.getLogger(__name__)

OLLAMA_DEFAULT_URL = "http://localhost:11434/api/generate"
OLLAMA_MODEL = "llama3:latest"
REQUEST_TIMEOUT_SECONDS = 5.0


class SituationSummary(BaseModel):
    summary: str = Field(..., description="Concise 2-3 sentence overview of the emergency cluster")
    key_risks: list[str] = Field(default_factory=list, description="Primary hazards identified")
    recommended_actions: list[str] = Field(
        default_factory=list, description="Advisory recommendations for authorities"
    )
    total_reports: int = Field(default=1)
    estimated_people_affected: int = Field(default=0)
    primary_category: str = Field(default="general")
    severity: str = Field(default="MEDIUM")
    is_fallback: bool = Field(
        default=False, description="True if generated by local deterministic summarizer"
    )


def generate_deterministic_summary(reports: list[dict[str, Any]]) -> SituationSummary:
    """Deterministic extractive summarizer used when Ollama is offline or times out."""
    count = len(reports)
    if count == 0:
        return SituationSummary(
            summary="No incident reports available for summarization.",
            total_reports=0,
            is_fallback=True,
        )

    # Aggregate categories, severities, and people counts
    categories: dict[str, int] = {}
    severities: dict[str, int] = {}
    total_people = 0
    locations = set()
    snippets = []

    for r in reports:
        cat = r.get("category", "other")
        sev = r.get("severity", "MEDIUM")
        categories[cat] = categories.get(cat, 0) + 1
        severities[sev] = severities.get(sev, 0) + 1
        total_people += int(r.get("people_count") or 0)
        loc = r.get("location_text") or r.get("location")
        if loc:
            locations.add(str(loc))
        text = r.get("raw_text") or r.get("text") or ""
        if text and len(snippets) < 3:
            snippets.append(text.strip()[:100])

    top_cat = max(categories, key=lambda k: categories[k])
    # Highest severity present
    sev_rank = {"CRITICAL": 4, "HIGH": 3, "MEDIUM": 2, "LOW": 1}
    top_sev = max(severities.keys(), key=lambda s: sev_rank.get(s, 0))

    loc_str = f" in {', '.join(sorted(locations)[:2])}" if locations else ""
    people_str = f" involving approximately {total_people} individuals" if total_people > 0 else ""

    summary_text = (
        f"Cluster of {count} reports indicates ongoing {top_cat.upper()} activity"
        f"{loc_str}{people_str}. Highest urgency level observed is {top_sev}. "
        f"Citizen reports highlight: {' // '.join(snippets)}."
    )

    # Derive risks & actions
    risks = []
    actions = []
    if top_cat == "flood":
        risks.extend(
            [
                "Rising water levels and residential inundation",
                "Marooned residents requiring watercraft",
            ]
        )
        actions.extend(
            [
                "Deploy rescue boats and inflatable rafts",
                "Dispatch emergency food and drinking water rations",
            ]
        )
    elif top_cat == "fire":
        risks.extend(["Rapid fire propagation to adjacent structures", "Toxic smoke inhalation"])
        actions.extend(
            ["Dispatch fire tenders with foam equipment", "Establish perimeter evacuation cordon"]
        )
    elif top_cat == "medical":
        risks.extend(
            ["Trauma victims with acute blood loss or cardiac symptoms", "Hospital transport delay"]
        )
        actions.extend(
            [
                "Deploy Advanced Life Support (ALS) ambulances",
                "Alert nearest district trauma center",
            ]
        )
    elif top_cat == "rescue":
        risks.extend(
            ["Structural collapse with trapped victims under debris", "Oxygen deprivation"]
        )
        actions.extend(
            [
                "Deploy urban search and rescue team with heavy cutters",
                "Deploy medical triage units",
            ]
        )
    else:
        risks.append("Civic disruption and utility interruption")
        actions.append("Coordinate municipal rapid-response inspection")

    return SituationSummary(
        summary=summary_text,
        key_risks=risks,
        recommended_actions=actions,
        total_reports=count,
        estimated_people_affected=total_people,
        primary_category=top_cat,
        severity=top_sev,
        is_fallback=True,
    )


def summarize_cluster(
    reports: list[dict[str, Any]],
    ollama_url: str = OLLAMA_DEFAULT_URL,
    model: str = OLLAMA_MODEL,
) -> SituationSummary:
    """Summarize a cluster of reports using local Ollama LLM with schema validation."""
    if not reports:
        return SituationSummary(summary="No reports provided.", total_reports=0, is_fallback=True)

    # Prepare prompt
    report_items = []
    for r in reports[:10]:
        cat = r.get("category", "incident")
        sev = r.get("severity", "UNK")
        text = r.get("raw_text") or r.get("text", "")
        report_items.append(f"- [{cat}/{sev}] {text}")
    report_texts = "\n".join(report_items)

    prompt = (
        "You are an emergency command-center assistant. "
        "Analyze these disaster reports and output ONLY a valid JSON object.\n"
        "Schema:\n"
        "{\n"
        '  "summary": "2-3 concise factual sentences summarizing the disaster cluster",\n'
        '  "key_risks": ["risk 1", "risk 2"],\n'
        '  "recommended_actions": ["action 1", "action 2"]\n'
        "}\n\n"
        f"Reports:\n{report_texts}\n\n"
        "Respond ONLY with valid JSON. No conversational filler."
    )

    # Attempt local Ollama inference
    try:
        with httpx.Client(timeout=REQUEST_TIMEOUT_SECONDS) as client:
            resp = client.post(
                ollama_url,
                json={
                    "model": model,
                    "prompt": prompt,
                    "stream": False,
                    "format": "json",
                },
            )
            if resp.status_code == 200:
                body = resp.json()
                raw_response = body.get("response", "")
                parsed = json.loads(raw_response)

                fallback = generate_deterministic_summary(reports)
                return SituationSummary(
                    summary=parsed.get("summary", fallback.summary),
                    key_risks=parsed.get("key_risks", fallback.key_risks),
                    recommended_actions=parsed.get(
                        "recommended_actions", fallback.recommended_actions
                    ),
                    total_reports=len(reports),
                    estimated_people_affected=fallback.estimated_people_affected,
                    primary_category=fallback.primary_category,
                    severity=fallback.severity,
                    is_fallback=False,
                )
    except Exception as exc:
        logger.info(
            "Ollama local LLM unavailable or timed out (%s), using deterministic summary.", exc
        )

    return generate_deterministic_summary(reports)
